def get_connection():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL is not set")

    return psycopg.connect(DATABASE_URL)


def init_database():
    with get_connection() as conn:
        with conn.cursor() as cur:

            # WORKERS
            cur.execute(
                "CREATE TABLE IF NOT EXISTS workers "
                "(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                "telegram_id BIGINT, name TEXT, phone TEXT, service TEXT, "
                "area TEXT, price TEXT, created_at TIMESTAMPTZ DEFAULT NOW())"
            )

            # ORDERS
            cur.execute(
                "CREATE TABLE IF NOT EXISTS orders "
                "(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                "telegram_id BIGINT, name TEXT, phone TEXT, service TEXT, "
                "address TEXT, problem TEXT, created_at TIMESTAMPTZ DEFAULT NOW())"
            )

            # ANNOUNCEMENTS
            cur.execute(
                "CREATE TABLE IF NOT EXISTS announcements "
                "(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                "telegram_id BIGINT, name TEXT, phone TEXT, service TEXT, "
                "address TEXT, budget TEXT, details TEXT, "
                "created_at TIMESTAMPTZ DEFAULT NOW())"
            )

            # Агар эски жадвалларда telegram_id йўқ бўлса,
            # автоматик қўшилади.
            cur.execute(
                "ALTER TABLE workers "
                "ADD COLUMN IF NOT EXISTS telegram_id BIGINT"
            )

            cur.execute(
                "ALTER TABLE orders "
                "ADD COLUMN IF NOT EXISTS telegram_id BIGINT"
            )

            cur.execute(
                "ALTER TABLE announcements "
                "ADD COLUMN IF NOT EXISTS telegram_id BIGINT"
            )

        conn.commit()


