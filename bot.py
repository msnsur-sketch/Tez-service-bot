async def customer_problem(update, context):

    problem = update.message.text.strip()

    if not problem:
        await update.message.reply_text(
            "❗ Муаммони ёзинг:"
        )
        return PROBLEM

    context.user_data["problem"] = problem

    user = update.effective_user
    data = context.user_data

    order_id = None
    matching_workers = []

    # =========================
    # 1. SAVE ORDER + FIND WORKERS
    # =========================

    with get_connection() as conn:
        with conn.cursor() as cur:

            # Буюртмани Supabase'га сақлаймиз
            cur.execute(
                "INSERT INTO orders "
                "(telegram_id, name, phone, service, address, problem) "
                "VALUES (%s, %s, %s, %s, %s, %s) "
                "RETURNING id",
                (
                    user.id,
                    data["name"],
                    data["phone"],
                    data["service"],
                    data["address"],
                    data["problem"],
                ),
            )

            result = cur.fetchone()

            if result:
                order_id = result[0]

            # Барча усталарни оламиз
            cur.execute(
                "SELECT telegram_id, name, service, area, price "
                "FROM workers "
                "ORDER BY id DESC"
            )

            rows = cur.fetchall()

            # Танланган хизматга мос усталарни аниқлаймиз
            for row in rows:

                worker_telegram_id = row[0]
                worker_service = row[2]

                if service_matches(
                    data["service"],
                    worker_service,
                ):
                    matching_workers.append(row)

        conn.commit()

    # =========================
    # 2. SEND ORDER TO WORKERS
    # =========================

    sent_count = 0

    for worker in matching_workers:

        worker_telegram_id = worker[0]
        worker_name = worker[1]

        # Telegram ID бўлмаса, хабар юбормаймиз
        if not worker_telegram_id:
            logger.warning(
                f"Worker {worker_name} has no telegram_id"
            )
            continue

        worker_message = (
            "🔔 ЯНГИ БУЮРТМА!\n\n"
            f"📌 Буюртма №{order_id}\n\n"
            f"👤 Исм: {data['name']}\n"
            f"📞 Телефон: {data['phone']}\n"
            f"🔧 Хизмат: {data['service']}\n"
            f"📍 Манзил: {data['address']}\n"
            f"📝 Муаммо: {data['problem']}\n\n"
            "📲 Мижоз билан боғланинг."
        )

        try:

            await context.bot.send_message(
                chat_id=int(worker_telegram_id),
                text=worker_message,
            )

            sent_count += 1

            logger.info(
                f"Order #{order_id} sent to worker "
                f"{worker_name} "
                f"(telegram_id={worker_telegram_id})"
            )

        except Exception as e:

            logger.exception(
                f"Failed to send order #{order_id} "
                f"to worker {worker_name} "
                f"(telegram_id={worker_telegram_id}): {e}"
            )

    # =========================
    # 3. CUSTOMER CONFIRMATION
    # =========================

    if sent_count > 0:

        worker_result_text = (
            f"👨‍🔧 {sent_count} та мос устага "
            "буюртма юборилди."
        )

    elif matching_workers:

        worker_result_text = (
            "⚠️ Мос уста топилди, лекин ҳозирча "
            "унга Telegram хабарини юбориб бўлмади."
        )

    else:

        worker_result_text = (
            "ℹ️ Ҳозирча бу хизмат бўйича "
            "мос уста топилмади."
        )

    await update.message.reply_text(
        "🔔 ЯНГИ БУЮРТМА!\n\n"
        f"📌 Буюртма №{order_id}\n"
        f"👤 Исм: {data['name']}\n"
        f"📞 Телефон: {data['phone']}\n"
        f"🔧 Хизмат: {data['service']}\n"
        f"📍 Манзил: {data['address']}\n"
        f"📝 Муаммо: {data['problem']}\n\n"
        "✅ Буюртмангиз қабул қилинди.\n"
        f"{worker_result_text}",
        reply_markup=main_menu(),
    )

    context.user_data.clear()

    return ConversationHandler.END


