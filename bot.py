async def service_selected(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):

    service = update.message.text

    context.user_data.clear()
    context.user_data["service"] = service

    workers = []

    with get_connection() as conn:
        with conn.cursor() as cur:

            cur.execute(
                "SELECT name, service, area, price, phone "
                "FROM workers ORDER BY id DESC"
            )

            rows = cur.fetchall()

            for row in rows:

                worker_service = row[1]

                if service_matches(
                    service,
                    worker_service,
                ):
                    workers.append(row)

    if workers:

        message = "👨‍🔧 Мос усталар:\n\n"

        for i, row in enumerate(workers[:10], 1):

            name, worker_service, area, price, phone = row

            message += (
                f"#{i} {name}\n"
                f"🔧 Хизмат: {worker_service}\n"
                f"📍 Ҳудуд: {area}\n"
                f"💰 Нархи: {price}\n"
                f"📞 Телефон: {phone}\n\n"
            )

        await update.message.reply_text(message)

    else:

        await update.message.reply_text(
            "😔 Ҳозирча бу хизмат бўйича "
            "рўйхатдан ўтган уста топилмади."
        )

    await update.message.reply_text(
        f"Танланган хизмат: {service}\n\n"
        "👤 Исмингизни ёзинг:"
    )

    return NAME


