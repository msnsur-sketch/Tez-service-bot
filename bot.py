async def admin_workers(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):
    if not await admin_only(update):
        return

    with get_connection() as conn:
        with conn.cursor() as cur:

            cur.execute(
                """
                SELECT
                    id,
                    telegram_id,
                    name,
                    phone,
                    service,
                    area,
                    price,
                    country_name,
                    city,
                    currency,
                    COALESCE(is_active, TRUE)
                FROM workers
                ORDER BY id DESC
                """
            )

            rows = cur.fetchall()

    if not rows:
        await update.message.reply_text(
            "Усталар йўқ."
        )
        return

    lines = [
        "👨‍🔧 УСТАЛАР\n"
    ]

    for row in rows:

        (
            wid,
            tid,
            name,
            phone,
            service,
            area,
            price,
            country,
            city,
            currency,
            active,
        ) = row

        status = "🟢" if active else "🔴"

        lines.append(
            f"#{wid} {status} {name}\n"
            f"🌍 {country or '-'}\n"
            f"🏙 {city or '-'}\n"
            f"🔧 {service}\n"
            f"📍 {area}\n"
            f"💰 {price} {currency or ''}\n"
            f"📞 {phone}\n"
            f"🆔 {tid}"
        )

    await update.message.reply_text(
        "\n\n".join(lines)[:4000]
    )


