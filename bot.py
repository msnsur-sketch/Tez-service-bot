async def accept_order_callback(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):
    query = update.callback_query

    await query.answer()

    user = update.effective_user

    try:
        order_id = int(
            query.data.split(":", 1)[1]
        )
    except Exception:

        await query.message.reply_text(
            "❗ Буюртма рақами нотўғри."
        )

        return

    with get_connection() as conn:
        with conn.cursor() as cur:

            # ------------------------------------------------
            # FIND WORKER
            # ------------------------------------------------

            cur.execute(
                """
                SELECT
                    id,
                    name,
                    phone,
                    is_active
                FROM workers
                WHERE telegram_id=%s
                ORDER BY id DESC
                LIMIT 1
                """,
                (user.id,),
            )

            worker = cur.fetchone()

            if not worker:

                await query.message.reply_text(
                    "❗ Сизда уста профили "
                    "мавжуд эмас."
                )

                return

            if worker[3] is False:

                await query.message.reply_text(
                    "🔴 Профилингиз нофаол.\n\n"
                    "Янги буюртмаларни "
                    "қабул қила олмайсиз."
                )

                return

            worker_id = worker[0]
            worker_name = worker[1]
            worker_phone = worker[2]

            # ------------------------------------------------
            # ACCEPT ONLY NEW ORDER
            # ------------------------------------------------

            cur.execute(
                """
                UPDATE orders
                SET
                    status='accepted',
                    accepted_worker_id=%s,
                    accepted_worker_name=%s,
                    accepted_at=NOW()
                WHERE id=%s
                  AND status='new'
                RETURNING
                    telegram_id,
                    name,
                    phone,
                    service,
                    address,
                    problem
                """,
                (
                    worker_id,
                    worker_name,
                    order_id,
                ),
            )

            order = cur.fetchone()

        conn.commit()

    # --------------------------------------------------------
    # ORDER ALREADY ACCEPTED
    # --------------------------------------------------------

    if not order:

        await query.message.reply_text(
            "⚠️ Бу буюртма аллақачон "
            "бошқа уста томонидан қабул "
            "қилинган."
        )

        try:
            await query.edit_message_reply_markup(
                reply_markup=None
            )
        except Exception:
            pass

        return

    # --------------------------------------------------------
    # ORDER DATA
    # --------------------------------------------------------

    customer_id = order[0]
    customer_name = order[1]
    customer_phone = order[2]
    service = order[3]
    address = order[4]
    problem = order[5]

    # Remove accept button
    try:

        await query.edit_message_reply_markup(
            reply_markup=None
        )

    except Exception:
        pass

    # --------------------------------------------------------
    # WORKER CONFIRMATION
    # --------------------------------------------------------

    await query.message.reply_text(
        f"✅ Буюртма #{order_id} "
        "сиз томонингиздан қабул қилинди!\n\n"
        f"👤 Мижоз: {customer_name}\n"
        f"📞 Мижоз телефони: {customer_phone}\n"
        f"🔧 Хизмат: {service}\n"
        f"📍 Манзил: {address}\n"
        f"📝 Муаммо: {problem}"
    )

    # --------------------------------------------------------
    # CUSTOMER NOTIFICATION
    # --------------------------------------------------------

    try:

        await context.bot.send_message(
            chat_id=customer_id,
            text=(
                "✅ БУЮРТМАНГИЗНИ УСТА ҚАБУЛ ҚИЛДИ!\n\n"
                f"👨‍🔧 Уста: {worker_name}\n"
                f"📞 Устанинг рақами: {worker_phone}\n\n"
                f"🔧 Хизмат: {service}\n"
                f"📍 Манзил: {address}"
            ),
        )

        logger.info(
            "✅ Customer %s notified about "
            "accepted order #%s",
            customer_id,
            order_id,
        )

    except Exception as exc:

        logger.exception(
            "❌ Customer notification failed: %s",
            exc,
        )


