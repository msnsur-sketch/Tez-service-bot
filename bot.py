async def service_selected(update: Update, context: ContextTypes.DEFAULT_TYPE):

    text = update.message.text

    service = normalize_service_name(text)

    context.user_data["service"] = text

    workers = []

    with get_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT name, service, area, price, phone
                FROM workers
                """
            )

            rows = cur.fetchall()

            for row in rows:
                worker_name, worker_service, area, price, phone = row

                if service in normalize_service_name(worker_service):
                    workers.append(row)

    if workers:
        message = "👨‍🔧 Мос усталар:\n\n"

        for i, row in enumerate(workers, 1):
            worker_name, worker_service, area, price, phone = row

            message += (
                f"#{i} {worker_name}\n"
                f"🔧 Хизмат: {worker_service}\n"
                f"📍 Ҳудуд: {area}\n"
                f"💰 Нархи: {price}\n"
                f"📞 Телефон: {phone}\n\n"
            )

        await update.message.reply_text(message)

    else:
        await update.message.reply_text(
            "😔 Ҳозирча бу хизмат бўйича рўйхатдан ўтган уста топилмади."
        )

    await update.message.reply_text(
        f"Танланган хизмат: {text}\n\n"
        "👤 Исмингизни ёзинг:"
    )

    return NAME


