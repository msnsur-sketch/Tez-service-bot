async def customer_problem(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):
    problem = update.message.text.strip()

    if not problem:
        await update.message.reply_text(
            "❗ Муаммони ёзинг."
        )
        return ORDER_PROBLEM

    data = context.user_data.get(
        "order_data"
    )

    if not data:
        await update.message.reply_text(
            "⚠️ Буюртма маълумотлари топилмади.\n"
            "Қайтадан буюртма беринг.",
            reply_markup=main_keyboard(),
        )
        return ConversationHandler.END

    required = [
        "service",
        "country_code",
        "country",
        "city",
        "currency",
        "name",
        "phone",
        "address",
    ]

    if not all(data.get(x) for x in required):
        await update.message.reply_text(
            "⚠️ Буюртма маълумотлари тўлиқ эмас.\n"
            "Қайтадан буюртма беринг.",
            reply_markup=main_keyboard(),
        )
        context.user_data.pop(
            "order_data",
            None,
        )
        return ConversationHandler.END

    user = update.effective_user

    # --------------------------------------------------------
    # SAVE ORDER
    # --------------------------------------------------------

    with get_connection() as conn:
        with conn.cursor() as cur:

            cur.execute(
                """
                INSERT INTO orders
                (
                    telegram_id,
                    name,
                    phone,
                    service,
                    address,
                    problem,
                    status,
                    country_code,
                    country_name,
                    city,
                    currency
                )
                VALUES
                (
                    %s,%s,%s,%s,%s,%s,'new',
                    %s,%s,%s,%s
                )
                RETURNING id
                """,
                (
                    user.id,
                    data["name"],
                    data["phone"],
                    data["service"],
                    data["address"],
                    problem,
                    data["country_code"],
                    data["country"],
                    data["city"],
                    data["currency"],
                ),
            )

            order_id = cur.fetchone()[0]

            # ------------------------------------------------
            # ONLY SAME COUNTRY + SAME CITY + ACTIVE
            # ------------------------------------------------

            cur.execute(
                """
                SELECT
                    telegram_id,
                    name,
                    service,
                    area,
                    price,
                    currency
                FROM workers
                WHERE COALESCE(is_active, TRUE)=TRUE
                  AND telegram_id IS NOT NULL
                  AND country_code=%s
                  AND city=%s
                ORDER BY id DESC
                """,
                (
                    data["country_code"],
                    data["city"],
                ),
            )

            workers = cur.fetchall()

        conn.commit()

    # --------------------------------------------------------
    # WORKER MESSAGE
    # --------------------------------------------------------

    message = (
        f"🔔 ЯНГИ БУЮРТМА #{order_id}\n\n"
        f"🌍 Давлат: {data['country']}\n"
        f"🏙 Шаҳар: {data['city']}\n"
        f"🔧 Хизмат: {data['service']}\n"
        f"👤 Мижоз: {data['name']}\n"
        f"📞 Телефон: {data['phone']}\n"
        f"📍 Манзил: {data['address']}\n"
        f"📝 Муаммо: {problem}\n\n"
        "Буюртмани олиш учун тугмани босинг."
    )

    sent_ids = set()
    notified_count = 0

    for (
        worker_telegram_id,
        worker_name,
        worker_service,
        worker_area,
        worker_price,
        worker_currency,
    ) in workers:

        if not worker_telegram_id:
            continue

        if worker_telegram_id in sent_ids:
            continue

        if not service_matches(
            data["service"],
            worker_service,
        ):
            logger.info(
                "Order #%s service mismatch: "
                "worker=%s service=%s requested=%s",
                order_id,
                worker_name,
                worker_service,
                data["service"],
            )
            continue

        sent_ids.add(
            worker_telegram_id
        )

        keyboard = InlineKeyboardMarkup(
            [
                [
                    InlineKeyboardButton(
                        "✅ Буюртмани оламан",
                        callback_data=(
                            f"accept_order:{order_id}"
                        ),
                    )
                ]
            ]
        )

        try:

            await context.bot.send_message(
                chat_id=worker_telegram_id,
                text=message,
                reply_markup=keyboard,
            )

            notified_count += 1

            logger.info(
                "✅ Order #%s sent to worker "
                "%s (%s)",
                order_id,
                worker_name,
                worker_telegram_id,
            )

        except Exception as exc:

            logger.exception(
                "❌ Worker notification failed "
                "for %s (%s): %s",
                worker_name,
                worker_telegram_id,
                exc,
            )

    # --------------------------------------------------------
    # CUSTOMER CONFIRMATION
    # --------------------------------------------------------

    if notified_count:

        confirmation = (
            f"✅ Буюртмангиз қабул қилинди!\n\n"
            f"Буюртма: #{order_id}\n"
            f"🌍 {data['country']}\n"
            f"🏙 {data['city']}\n"
            f"🔧 {data['service']}\n\n"
            f"👨‍🔧 {notified_count} та мос фаол "
            "устага хабар юборилди.\n\n"
            "Уста қабул қилса, сизга "
            "унинг маълумотлари келади."
        )

    else:

        confirmation = (
            f"✅ Буюртмангиз қабул қилинди!\n\n"
            f"Буюртма: #{order_id}\n"
            f"🌍 {data['country']}\n"
            f"🏙 {data['city']}\n\n"
            "⚠️ Ҳозирча бу шаҳарда "
            "мос фаол уста топилмади."
        )

    await update.message.reply_text(
        confirmation,
        reply_markup=main_keyboard(),
    )

    context.user_data.pop(
        "order_data",
        None,
    )

    return ConversationHandler.END


