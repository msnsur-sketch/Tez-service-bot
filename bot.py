def get_connection():
    return psycopg.connect(
        DATABASE_URL,
        connect_timeout=10,
    )


def init_database():
    with get_connection() as conn:
        with conn.cursor() as cur:

            # USERS
            cur.execute(
                """
                CREATE TABLE IF NOT EXISTS user_profiles (
                    telegram_id BIGINT PRIMARY KEY,
                    country_code TEXT,
                    country_name TEXT,
                    city TEXT,
                    currency TEXT,
                    created_at TIMESTAMPTZ DEFAULT NOW(),
                    updated_at TIMESTAMPTZ DEFAULT NOW()
                )
                """
            )

            # WORKERS
            cur.execute(
                """
                CREATE TABLE IF NOT EXISTS workers (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    telegram_id BIGINT,
                    name TEXT,
                    phone TEXT,
                    service TEXT,
                    area TEXT,
                    price TEXT,
                    created_at TIMESTAMPTZ DEFAULT NOW()
                )
                """
            )

            for column in [
                "is_active BOOLEAN DEFAULT TRUE",
                "country_code TEXT",
                "country_name TEXT",
                "city TEXT",
                "currency TEXT",
            ]:
                cur.execute(
                    f"ALTER TABLE workers ADD COLUMN IF NOT EXISTS {column}"
                )

            cur.execute(
                """
                UPDATE workers
                SET is_active=TRUE
                WHERE is_active IS NULL
                """
            )

            # ORDERS
            cur.execute(
                """
                CREATE TABLE IF NOT EXISTS orders (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    telegram_id BIGINT,
                    name TEXT,
                    phone TEXT,
                    service TEXT,
                    address TEXT,
                    problem TEXT,
                    created_at TIMESTAMPTZ DEFAULT NOW()
                )
                """
            )

            for column in [
                "status TEXT DEFAULT 'new'",
                "accepted_worker_id BIGINT",
                "accepted_worker_name TEXT",
                "accepted_at TIMESTAMPTZ",
                "country_code TEXT",
                "country_name TEXT",
                "city TEXT",
                "currency TEXT",
            ]:
                cur.execute(
                    f"ALTER TABLE orders ADD COLUMN IF NOT EXISTS {column}"
                )

            cur.execute(
                """
                UPDATE orders
                SET status='new'
                WHERE status IS NULL
                """
            )

            # ANNOUNCEMENTS
            cur.execute(
                """
                CREATE TABLE IF NOT EXISTS announcements (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    telegram_id BIGINT,
                    name TEXT,
                    phone TEXT,
                    service TEXT,
                    address TEXT,
                    budget TEXT,
                    details TEXT,
                    created_at TIMESTAMPTZ DEFAULT NOW()
                )
                """
            )

            for column in [
                "country_code TEXT",
                "country_name TEXT",
                "city TEXT",
                "currency TEXT",
            ]:
                cur.execute(
                    f"ALTER TABLE announcements ADD COLUMN IF NOT EXISTS {column}"
                )

            # INDEXES
            cur.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_workers_telegram_id
                ON workers(telegram_id)
                """
            )

            cur.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_workers_city_country
                ON workers(country_code, city)
                """
            )

            cur.execute(
                """
                CREATE INDEX IF NOT EXISTS idx_orders_status
                ON orders(status)
                """
            )

        conn.commit()

    logger.info("Database initialized successfully")


