            cur.execute(
                """
                SELECT
                    telegram_id,
                    name,
                    service,
                    area,
                    price,
                    currency
                FROM workers
                WHERE COALESCE(is_active,TRUE)=TRUE
                  AND telegram_id IS NOT NULL
                  AND country_code=%s
                  AND city=%s
                ORDER BY id DESC
                """,
                (
                    data["country_code"],
                    data["city"],
                ),
            )

