def normalize_service_name(text):
    if not text:
        return ""

    text = str(text).casefold()

    # Remove emojis
    text = re.sub(
        r"[🔧⚡📱💻🧹🪑👨‍🔧]",
        "",
        text,
    )

    replacements = {
        "а": "a",
        "б": "b",
        "в": "v",
        "г": "g",
        "д": "d",
        "е": "e",
        "ё": "yo",
        "ж": "j",
        "з": "z",
        "и": "i",
        "й": "y",
        "к": "k",
        "л": "l",
        "м": "m",
        "н": "n",
        "о": "o",
        "п": "p",
        "р": "r",
        "с": "s",
        "т": "t",
        "у": "u",
        "ф": "f",
        "х": "x",
        "ц": "ts",
        "ч": "ch",
        "ш": "sh",
        "щ": "sh",
        "ъ": "",
        "ы": "y",
        "ь": "",
        "э": "e",
        "ю": "yu",
        "я": "ya",
        "қ": "q",
        "ғ": "g",
        "ҳ": "h",
        "ў": "o",
    }

    for old, new in replacements.items():
        text = text.replace(old, new)

    text = re.sub(
        r"[^a-z0-9\s]",
        " ",
        text,
    )

    text = re.sub(
        r"\s+",
        " ",
        text,
    )

    return text.strip()


def canonical_service(text):
    normalized = normalize_service_name(text)

    if not normalized:
        return ""

    # Computer
    if (
        "kompyuter" in normalized
        or "komyuter" in normalized
        or "komputer" in normalized
    ):
        return "kompyuter"

    # Plumbing
    if (
        "santexnik" in normalized
        or "santehnik" in normalized
    ):
        return "santexnik"

    # Electrician
    if "elektrik" in normalized:
        return "elektrik"

    # Phone
    if "telefon" in normalized:
        return "telefon"

    # Cleaning
    if (
        "uy tozalash" in normalized
        or "tozalash" in normalized
    ):
        return "tozalash"

    # Furniture
    if "mebel" in normalized:
        return "mebel"

    return normalized


def service_matches(
    selected_service,
    worker_services,
):
    selected = canonical_service(
        selected_service
    )

    if not selected or not worker_services:
        return False

    parts = re.split(
        r"[,;/\n]+",
        str(worker_services),
    )

    for part in parts:
        if canonical_service(part) == selected:
            return True

    return False


